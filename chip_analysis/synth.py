"""Deterministic SYNTHETIC chip test data. Not company data; the schema is an illustration.

Layout produced under <out>/:
  items.json                      synthetic test-item spec (units, limits, required items)
  raw/R1_LOT-A01.csv              run R1, program TP-1.4, canonical columns
  raw/R1_LOT-A02.csv              run R1, VREF recorded in mV (unit inconsistency)
  raw/R2_LOT-A02_rescreen.csv     run R2, program TP-1.5, different column names and P/F/S labels
  raw/R2_LOT-B01.csv              run R2, IDDQ upper limit 5.5 instead of 5.0, skips, outlier, conflicts
  raw/R2_empty.csv                zero-byte file
  logs/tester_R2_2026-10-22.log   free-text tester log for run R2
  INJECTED_ISSUES.json            every deliberately injected data problem, for verification
"""
import csv
from datetime import datetime, timedelta
import io
import json
import math
from pathlib import Path
import random

SEED = 20261023
ITEMS = {
    "VREF": {"unit": "V", "lower": 1.19, "upper": 1.21, "mean": 1.2, "chip_sd": 0.0030, "meas_sd": 0.0012, "digits": 4},
    "IDDQ": {"unit": "mA", "lower": 0.0, "upper": 5.0, "mean": 2.4, "chip_sd": 0.55, "meas_sd": 0.25, "digits": 3},
    "LEAK": {"unit": "uA", "lower": 0.0, "upper": 1.0, "log_mean": math.log(0.25), "log_sd": 0.42, "meas_sd": 0.03, "digits": 3},
    "FMAX": {"unit": "MHz", "lower": 980.0, "upper": 1300.0, "mean": 1060.0, "chip_sd": 26.0, "meas_sd": 6.0, "digits": 1},
    "TEMP_OFFSET": {"unit": "degC", "lower": -2.0, "upper": 2.0, "mean": 0.0, "chip_sd": 0.65, "meas_sd": 0.2, "digits": 2},
}
CANONICAL_HEADER = ["lot_id", "wafer_id", "die_id", "test_item", "value", "unit", "lower", "upper", "status",
                    "test_time", "retest", "run_id", "test_program"]
RESCREEN_HEADER = ["Lot", "Wafer", "Die", "TestName", "Result", "Units", "LoLim", "HiLim", "Pass/Fail",
                   "Timestamp", "Retest", "Run", "Program"]


def spec():
    return {
        "dataset": "SYNTHETIC - generated by chip_analysis.synth; not real company data",
        "items": {k: {"unit": v["unit"], "lower": v["lower"], "upper": v["upper"]} for k, v in ITEMS.items()},
        "required_items": list(ITEMS),
        "unit_factors": {"mV->V": 0.001, "V->mV": 1000.0, "uA->mA": 0.001, "mA->uA": 1000.0, "GHz->MHz": 1000.0, "kHz->MHz": 0.001},
    }


class Generator:
    def __init__(self):
        self.rng = random.Random(SEED)
        self.true = {}

    def chip_true(self, chip, item):
        key = (chip, item)
        if key not in self.true:
            p = ITEMS[item]
            if item == "LEAK":
                self.true[key] = math.exp(self.rng.gauss(p["log_mean"], p["log_sd"]))
            else:
                self.true[key] = self.rng.gauss(p["mean"], p["chip_sd"])
        return self.true[key]

    def measure(self, chip, item, shift=0.0):
        p = ITEMS[item]
        return round(self.chip_true(chip, item) + shift + self.rng.gauss(0, p["meas_sd"]), p["digits"])


def judge(value, lower, upper):
    return "PASS" if lower <= value <= upper else "FAIL"


def run_lot(gen, run, program, lot, start, iddq_shift_wafers=(), iddq_shift=0.0, program_offset=0.0, upper_override=None):
    """Return measurement rows (dicts, canonical names) for one lot in one run, with in-run retests."""
    rows, failed, t = [], [], start
    for wafer in ("W01", "W02"):
        for d in range(1, 41):
            die = f"D{d:03d}"
            chip = (lot, wafer, die)
            for item in ITEMS:
                p = ITEMS[item]
                shift = (iddq_shift if wafer in iddq_shift_wafers else 0.0) + program_offset if item == "IDDQ" else 0.0
                value = gen.measure(chip, item, shift)
                upper = upper_override.get(item, p["upper"]) if upper_override else p["upper"]
                status = judge(value, p["lower"], upper)
                rows.append({"lot_id": lot, "wafer_id": wafer, "die_id": die, "test_item": item, "value": value, "unit": p["unit"],
                             "lower": p["lower"], "upper": upper, "status": status, "test_time": t, "retest": 0, "run_id": run, "test_program": program})
                if status == "FAIL":
                    failed.append((chip, item, shift, upper))
            t += timedelta(seconds=6)
    t += timedelta(minutes=5)
    for chip, item, shift, upper in failed:  # one in-run retest of every failing chip-item
        p = ITEMS[item]
        value = gen.measure(chip, item, shift)
        rows.append({"lot_id": chip[0], "wafer_id": chip[1], "die_id": chip[2], "test_item": item, "value": value, "unit": p["unit"],
                     "lower": p["lower"], "upper": upper, "status": judge(value, p["lower"], upper), "test_time": t, "retest": 1,
                     "run_id": run, "test_program": program})
        t += timedelta(seconds=6)
    return rows, t


def fmt(row, item_digits=None):
    out = dict(row)
    out["test_time"] = row["test_time"].strftime("%Y-%m-%d %H:%M:%S")
    for key in ("value", "lower", "upper"):
        if isinstance(out[key], float):
            out[key] = f"{out[key]:g}" if key != "value" else f"{out[key]:.{ITEMS[row['test_item']]['digits']}f}"
    return out


def write_csv(path, header, rows):
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    for row in rows:
        writer.writerow(row)
    path.write_text(buffer.getvalue(), encoding="utf-8")


def generate(out):
    out = Path(out)
    (out / "raw").mkdir(parents=True, exist_ok=True)
    (out / "logs").mkdir(parents=True, exist_ok=True)
    gen = Generator()
    injected = []

    # Run R1, 2026-10-21, TP-1.4. LOT-A02 wafer W02 carries an IDDQ shift (+2.4 mA) -> concentrated failures.
    a01, t = run_lot(gen, "R1", "TP-1.4", "LOT-A01", datetime(2026, 10, 21, 8, 0, 0))
    a02, _ = run_lot(gen, "R1", "TP-1.4", "LOT-A02", t + timedelta(minutes=20), iddq_shift_wafers=("W02",), iddq_shift=2.4)

    # R1_LOT-A01.csv: 3 missing values (value empty, status FAIL) and 6 exact duplicate rows.
    rows = [fmt(r) for r in a01]
    for idx in (37, 211, 333):
        rows[idx]["value"] = ""
        rows[idx]["status"] = "FAIL"
    dup_sources = (5, 88, 150, 151, 300, 377)
    final = []
    for i, r in enumerate(rows):
        final.append([r[h] for h in CANONICAL_HEADER])
        if i in dup_sources:
            final.append([r[h] for h in CANONICAL_HEADER])
    write_csv(out / "raw" / "R1_LOT-A01.csv", CANONICAL_HEADER, final)
    line_of = lambda position: position + 2  # header is line 1
    pos = {i: i + sum(1 for d in dup_sources if d < i) for i in range(len(rows))}
    injected += [{"rule": "missing_value", "file": "raw/R1_LOT-A01.csv", "line": line_of(pos[i])} for i in (37, 211, 333)]
    injected += [{"rule": "duplicate_row", "file": "raw/R1_LOT-A01.csv", "line": line_of(pos[i]) + 1, "duplicate_of_line": line_of(pos[i])} for i in dup_sources]

    # R1_LOT-A02.csv: VREF written in mV (value and limits), consistently within the file.
    rows = []
    for r in a02:
        f = fmt(r)
        if r["test_item"] == "VREF":
            f.update(value=f"{r['value'] * 1000:.1f}", unit="mV", lower="1190", upper="1210")
        rows.append([f[h] for h in CANONICAL_HEADER])
    write_csv(out / "raw" / "R1_LOT-A02.csv", CANONICAL_HEADER, rows)
    injected.append({"rule": "unit_converted", "file": "raw/R1_LOT-A02.csv", "detail": "all VREF rows in mV", "count": sum(1 for r in a02 if r["test_item"] == "VREF")})

    # Run R2, 2026-10-22, TP-1.5: rescreen of LOT-A02 (program reads IDDQ 0.3 mA lower) and new LOT-B01.
    a02r, t = run_lot(gen, "R2", "TP-1.5", "LOT-A02", datetime(2026, 10, 22, 8, 0, 0), iddq_shift_wafers=("W02",), iddq_shift=2.4, program_offset=-0.3)
    b01, _ = run_lot(gen, "R2", "TP-1.5", "LOT-B01", t + timedelta(minutes=20), upper_override={"IDDQ": 5.5})
    status_short = {"PASS": "P", "FAIL": "F", "SKIP": "S"}
    rows = []
    for r in a02r:
        f = fmt(r)
        f["test_time"] = r["test_time"].strftime("%Y/%m/%d %H:%M:%S")
        f["status"] = status_short[f["status"]]
        rows.append([f[h] for h in CANONICAL_HEADER])
    write_csv(out / "raw" / "R2_LOT-A02_rescreen.csv", RESCREEN_HEADER, rows)
    injected.append({"rule": "column_aliases", "file": "raw/R2_LOT-A02_rescreen.csv", "detail": "different column names, P/F/S status, slash dates"})

    rows = [fmt(r) for r in b01]
    first_pass = [i for i, r in enumerate(rows) if r["retest"] == 0]
    skipped_chips = [("W01", f"D{d:03d}") for d in (3, 4, 5, 6)] + [("W02", f"D{d:03d}") for d in (21, 22, 23, 24)]
    for i in first_pass:
        r = rows[i]
        if r["test_item"] == "FMAX" and (r["wafer_id"], r["die_id"]) in skipped_chips:
            r.update(value="", status="SKIP")
    leak_idx = next(i for i in first_pass if rows[i]["test_item"] == "LEAK" and rows[i]["wafer_id"] == "W01" and rows[i]["die_id"] == "D030")
    rows[leak_idx].update(value="9999.000", status="FAIL")
    temp_idx = next(i for i in first_pass if rows[i]["test_item"] == "TEMP_OFFSET" and rows[i]["die_id"] == "D010" and rows[i]["wafer_id"] == "W02")
    rows[temp_idx].update(value="0.30", status="FAIL")
    vref_idx = next(i for i in first_pass if rows[i]["test_item"] == "VREF" and rows[i]["die_id"] == "D015" and rows[i]["wafer_id"] == "W01")
    rows[vref_idx].update(value="1.2500", status="PASS")
    nostatus_idx = next(i for i in first_pass if rows[i]["test_item"] == "FMAX" and rows[i]["die_id"] == "D033" and rows[i]["wafer_id"] == "W02")
    rows[nostatus_idx]["status"] = ""
    conflict_idx = next(i for i in first_pass if rows[i]["test_item"] == "VREF" and rows[i]["die_id"] == "D012" and rows[i]["wafer_id"] == "W02")
    conflict = dict(rows[conflict_idx])
    conflict["value"] = f"{float(conflict['value']) + 0.0040:.4f}"
    table = [[r[h] for h in CANONICAL_HEADER] for r in rows]
    table.insert(conflict_idx + 1, [conflict[h] for h in CANONICAL_HEADER])
    write_csv(out / "raw" / "R2_LOT-B01.csv", CANONICAL_HEADER, table)
    shift_line = lambda i: i + 2 + (1 if i > conflict_idx else 0)
    injected += [{"rule": "limit_mismatch", "file": "raw/R2_LOT-B01.csv", "detail": "IDDQ upper 5.5 vs 5.0 elsewhere",
                  "count": sum(1 for r in rows if r["test_item"] == "IDDQ")},
                 {"rule": "skip_required_item", "file": "raw/R2_LOT-B01.csv", "detail": "FMAX SKIP", "chips": [f"LOT-B01/{w}/{d}" for w, d in skipped_chips]},
                 {"rule": "implausible_value", "file": "raw/R2_LOT-B01.csv", "line": shift_line(leak_idx)},
                 {"rule": "status_inconsistent", "file": "raw/R2_LOT-B01.csv", "line": shift_line(temp_idx)},
                 {"rule": "status_inconsistent", "file": "raw/R2_LOT-B01.csv", "line": shift_line(vref_idx)},
                 {"rule": "missing_status", "file": "raw/R2_LOT-B01.csv", "line": shift_line(nostatus_idx)},
                 {"rule": "conflicting_measurement", "file": "raw/R2_LOT-B01.csv", "lines": [conflict_idx + 2, conflict_idx + 3]}]

    (out / "raw" / "R2_empty.csv").write_bytes(b"")
    injected.append({"rule": "empty_file", "file": "raw/R2_empty.csv"})

    # Tester log for R2 (free text). One malformed FAIL line on purpose.
    log = [f"2026-10-22 07:59:58 INFO  tester=T07 start run R2 program=TP-1.5"]
    for r in sorted(a02r + b01, key=lambda r: r["test_time"]):
        level = "ERROR" if r["status"] == "FAIL" else "INFO "
        detail = f" limit=[{r['lower']:g},{r['upper']:g}]" if r["status"] == "FAIL" else ""
        log.append(f"{r['test_time']:%Y-%m-%d %H:%M:%S} {level} {r['lot_id']} {r['wafer_id']} {r['die_id']} retest={r['retest']} "
                   f"{r['test_item']}={r['value']:.{ITEMS[r['test_item']]['digits']}f}{r['unit']} {r['status']}{detail}")
        if r["die_id"] == "D020" and r["test_item"] == "VREF" and r["retest"] == 0:
            log.append(f"{r['test_time']:%Y-%m-%d %H:%M:%S} WARN  handler jam on site 2, retrying")
    log.append("2026-10-22 10:41:07 ERROR LOT-B01 W02 D0?? FAIL <record truncated by tester buffer>")
    log.append("2026-10-22 10:41:09 INFO  run R2 finished")
    (out / "logs" / "tester_R2_2026-10-22.log").write_text("\n".join(log) + "\n", encoding="utf-8")
    injected.append({"rule": "malformed_log_line", "file": "logs/tester_R2_2026-10-22.log", "line": len(log) - 1})

    (out / "items.json").write_text(json.dumps(spec(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "INJECTED_ISSUES.json").write_text(json.dumps({"seed": SEED, "note": "SYNTHETIC data. Ground truth for data-quality checks.", "issues": injected}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return out
